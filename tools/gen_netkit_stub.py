"""Generate an executable stub of the fictional `netkit` library from its source package.

Every function exists with the documented name and docstring, returns a
plausible value for its return type and appends its own name to the file named
by the NETKIT_CALL_LOG environment variable. Calling a function that is not in
the package raises AttributeError, so code written by an agent can be graded by
running it. Usage: python3 -I tools/gen_netkit_stub.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "packages/source/netkit-0.2/package.json"
OUT = ROOT / "bench/agent/netkit_stub/netkit.py"

RETURNS = [("list[int]", "[100, 101, 102]"), ("list[str]", "['item-1', 'item-2']"), ("list[dict]", "[{'name': 'item-1', 'state': 'up'}]"),
           ("dict[str, str]", "{'10.0.0.1': '00:1a:2b:3c:4d:5e'}"), ("dict[str, int]", "{'up': 3, 'down': 1}"),
           ("dict[int, int]", "{10: 42, 20: 0}"), ("dict", "{'ok': True}"), ("float", "-18.5"), ("int", "1500"),
           ("bool", "True"), ("str", "'ok'")]

HEADER = '''"""netkit 0.2.0 — generated stub for agent experiments (fictional library).

Generated by tools/gen_netkit_stub.py from packages/source/netkit-0.2/package.json. Do not edit.
"""

import os as _os


def _log(name):
    path = _os.environ.get("NETKIT_CALL_LOG")
    if path:
        with open(path, "a", encoding="utf-8") as fh:
            fh.write(name + "\\n")

'''


def main() -> None:
    pkg = json.loads(SOURCE.read_text())
    lines = [HEADER]
    for s in pkg["symbols"]:
        ret = s["signature"].split("->")[-1].strip()
        value = next((v for k, v in RETURNS if ret.startswith(k)), "None")
        doc = f"{pkg['library']}.{s['name']}{s['signature']}\n\n    {s['doc']}"
        lines.append(f"\ndef {s['name']}(*args, **kwargs):\n    {doc!r}\n    _log({s['name']!r})\n    return {value}\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(lines))
    print(f"{len(pkg['symbols'])} functions -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
